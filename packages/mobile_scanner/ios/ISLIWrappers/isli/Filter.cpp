#include "Filter.h"

// NEON float 路径已移除（2026-08-04）：
//   原 NEON 版本使用 float 精度（vs 标量 double），导致手机与 PC 输出的滤波波形
//   有 ±1 像素差异。差异经二值化 -> wave2bits -> BCH 传播后，在 borderline 图像上
//   可产生错误码（FP）。实测 cache4 在 PC 端（标量 double）0 FP，手机端（NEON float）FP>0。
//   移除后确保全平台 bit-exact 一致。性能影响可忽略（27 抽头 × ～500 样本/边 × 4 边
//   ≈ 54K 乘加运算 ≈ 0.01ms/image，远低于 trace/curve_sample 耗时）。

double lp_filter_coef[] = {
    -0.007775715121256268,
    -0.007938974136595613,
    -0.009534265788246128,
    -0.008779578259641298,
    -0.004381884421750879,
    0.004666131585205163,
    0.0188044731228937,
    0.03764144706001848,
    0.05992101812383003,
    0.08357444021744635,
    0.10601855702701225,
    0.12454015906119098,
    0.13674393462068657,
    0.14100385434561774,
    0.13674393462068657,
    0.12454015906119098,
    0.10601855702701225,
    0.08357444021744635,
    0.05992101812383003,
    0.03764144706001848,
    0.0188044731228937,
    0.004666131585205163,
    -0.004381884421750879,
    -0.008779578259641298,
    -0.009534265788246128,
    -0.007938974136595613,
    -0.007775715121256268
};

void do_low_pass_filter(unsigned char* in, int len, unsigned char* out)
{
    int k = sizeof(lp_filter_coef) / sizeof(lp_filter_coef[0]) / 2;

    // 全平台统一标量 double 实现（bit-exact PC 与手机一致）
    for (int i = 0; i < len; i++) {
        int p = 0;
        double acc = 0;

        for (int j = i - k; j <= i + k; j++) {
            int m = j;
            if (m < 0)
                m += len;
            else if (m >= len)
                m -= len;

            acc += (in[m] * lp_filter_coef[p++]);
        }
        acc /= 1.208;
        if (acc < 0)
            acc = 0;
        else if (acc > 255)
            acc = 255;

        out[i] = (unsigned char)(acc + 0.5);
    }
}
