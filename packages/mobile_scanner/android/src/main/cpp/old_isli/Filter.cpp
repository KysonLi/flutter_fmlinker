void do_low_pass_filter(unsigned char* in, int len, unsigned char* out)
{
    int k = sizeof(lp_filter_coef) / sizeof(lp_filter_coef[0]) / 2;

    for (int i = 0; i < len; i++) {
        int p = 0;
        double acc = 0;
        
        for (int j = i - k; j <= i + k; j++){
            int m = j;
            if (m < 0)
                m += len;
            else if (m >= len)
                m -= len;
            
            acc += (in[m] * lp_filter_coef[p++]);
        }
        acc /= 1.208;
        if (acc < 0)
            acc = 0;
        else if (acc > 255)
            acc = 255;
        
        out[i] = (unsigned char)(acc + 0.5);
    }
}

